#!/usr/bin/env node
// Inline the real magpie icons into client.js.
//
// The icons in icons/ are the ones the magpie app itself ships: they were
// lifted from the asset bundle embedded in magpie.exe (a zip at the end of the
// binary, entries under assets/icons/<name>.svg|png) plus the QwenWork plugin
// icon magpie keeps in ~/.config/magpie/icons. The client plugin has no static
// asset route, so each icon is baked into client.js as a data URI between the
// ICONS markers. Monochrome mark files (fill="currentColor", or no fill at all)
// need a colour to be visible on the panel's dark surface: FILL supplies one.
//
//   node tools/embed-icons.mjs           rewrite the block in client.js
//   node tools/embed-icons.mjs --check    fail when the block is stale
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ICON_DIR = path.join(root, 'icons')
const CLIENT = path.join(root, 'client.js')
const BEGIN = '// <icons: generated by tools/embed-icons.mjs>'
const END = '// </icons>'

// key -> [file, colour for a monochrome mark]. Order is documentation order.
const FILL = {
  magpie: ['magpie.svg', '#ededf1'],
  dsh: ['dsh.png', ''],
  qoder: ['qoder.svg', '#4d6bfe'],
  zcode: ['zcode.png', ''],
  'workbuddy-color': ['workbuddy-color.svg', ''],
  'minimax-color': ['minimax-color.svg', ''],
  opencode: ['opencode.svg', '#ededf1'],
  qwenwork: ['qwenwork.svg', ''],
  'qwen-color': ['qwen-color.svg', ''],
  qwenpaw: ['qwenpaw.svg', ''],
  'deepseek-color': ['deepseek-color.svg', ''],
  'claude-color': ['claude-color.svg', ''],
  anthropic: ['anthropic.svg', '#e8a87c'],
  kimi: ['kimi.svg', '#ededf1'],
  moonshot: ['moonshot.svg', '#ededf1'],
  'zhipu-color': ['zhipu-color.svg', ''],
  'chatglm-color': ['chatglm-color.svg', ''],
  openai: ['openai.svg', '#ededf1'],
  'gemini-color': ['gemini-color.svg', ''],
  grok: ['grok.svg', '#ededf1'],
  mimocode: ['mimocode.svg', ''],
  'doubao-color': ['doubao-color.svg', ''],
}

function tidy(svg, fill) {
  let out = svg
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .trim()
  if (!fill) return out
  if (out.includes('currentColor')) return out.split('currentColor').join(fill)
  if (!/\sfill=/.test(out)) return out.replace(/<svg\b/, '<svg fill="' + fill + '"')
  return out
}

function dataUri(file, fill) {
  const raw = fs.readFileSync(path.join(ICON_DIR, file))
  if (file.endsWith('.png')) return 'data:image/png;base64,' + raw.toString('base64')
  const svg = tidy(raw.toString('utf8'), fill)
  return 'data:image/svg+xml;base64,' + Buffer.from(svg, 'utf8').toString('base64')
}

const lines = [BEGIN, 'const BRAND_ICONS = {']
let bytes = 0
for (const [key, [file, fill]] of Object.entries(FILL)) {
  const uri = dataUri(file, fill)
  bytes += uri.length
  lines.push('  ' + JSON.stringify(key) + ': ' + JSON.stringify(uri) + ',')
}
lines.push('}', END)
const block = lines.join('\n')

const src = fs.readFileSync(CLIENT, 'utf8')
const beginAt = src.indexOf(BEGIN)
const endAt = src.indexOf(END)
let next
if (beginAt >= 0 && endAt > beginAt) {
  next = src.slice(0, beginAt) + block + src.slice(endAt + END.length)
} else {
  const anchor = 'const PROVIDER_TINTS = {'
  const at = src.indexOf(anchor)
  if (at < 0) throw new Error('client.js has no PROVIDER_TINTS anchor to insert the icons before')
  next = src.slice(0, at) + block + '\n' + src.slice(at)
}

if (process.argv.includes('--check')) {
  if (next !== src) {
    console.error('client.js icon block is stale: run node tools/embed-icons.mjs')
    process.exit(1)
  }
  console.log('icon block is current (' + Object.keys(FILL).length + ' icons, ' + Math.round(bytes / 1024) + ' KB inline)')
} else {
  if (next !== src) fs.writeFileSync(CLIENT, next)
  console.log('embedded ' + Object.keys(FILL).length + ' icons, ' + Math.round(bytes / 1024) + ' KB inline')
}
